"""Desktop local-folder API schemas (M5, ADR 0503)."""

from __future__ import annotations

from typing import Literal
from uuid import UUID

from pydantic import Field

from app.schemas.auth import StrictModel


class FolderIn(StrictModel):
    folder_id: UUID = Field(description="Generated by the desktop app for this folder")
    name: str = Field(min_length=1, max_length=200, description="Folder label shown to the owner")
    device: str = Field(default="", max_length=200, description="Device label")


class SharingIn(StrictModel):
    groups: list[str] = Field(max_length=50, description="Group keys the owner belongs to")


class EventIn(StrictModel):
    event_id: UUID = Field(description="Idempotency key; a replay returns the first result")
    seq: int = Field(ge=0, description="Per-folder sequence; older events for a path are stale")
    op: Literal["upsert", "delete"]
    path: str = Field(min_length=1, max_length=1024, description="Relative path, '/' separated")
    sha256: str | None = Field(default=None, pattern=r"^[0-9a-f]{64}$")
    size: int | None = Field(default=None, ge=0)
    content_base64: str | None = Field(default=None, max_length=14_000_000)


class EventsIn(StrictModel):
    events: list[EventIn] = Field(min_length=1, max_length=50)
