"""Build the generated results tables from results/*.json.

    python -m bench.report                      # latest laptop + latest colab run -> reports/results-tables.md
    python -m bench.report --check              # fail if the committed tables are stale
    python -m bench.report results/a.json results/b.json
    python -m bench.report --colab-batch <id> --out results/<id>/results-tables.md   # notebook

With no paths and no --colab-batch, the runs come from results/selection.json if it exists: an
explicit, reviewed mapping of each adapter to exactly one run. Nothing is chosen because it
succeeded; results left out of the selection are listed under "Excluded results".

Every Colab adapter/fixture pair with no result is listed as PENDING, never as a score.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

from bench.adapters import ADAPTERS, CLOUD_CANDIDATES

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "reports" / "results-tables.md"
SELECTION = "selection.json"


class SelectionError(ValueError):
    """results/selection.json is inconsistent with the committed result files."""


def load_selection(results_dir: Path) -> tuple[list[Path], dict]:
    sel = json.loads((results_dir / SELECTION).read_text(encoding="utf-8"))
    paths: list[Path] = []
    owner: dict[str, str] = {}
    for entry in sel["selected"]:
        path = results_dir / f"{entry['run']}.json"
        if not path.exists():
            raise SelectionError(f"selected run {entry['run']} has no results file")
        doc = json.loads(path.read_text(encoding="utf-8"))
        if doc["environment"]["where"] != entry["where"]:
            raise SelectionError(f"run {entry['run']} is a {doc['environment']['where']} run, not {entry['where']}")
        present = {r["adapter"] for r in doc["results"]}
        for name in entry["adapters"]:
            if name not in ADAPTERS:
                raise SelectionError(f"unknown adapter {name!r} in selection")
            if name in owner:
                raise SelectionError(f"adapter {name} is selected from both {owner[name]} and {entry['run']}")
            if name not in present:
                raise SelectionError(f"run {entry['run']} has no results for adapter {name}")
            owner[name] = entry["run"]
        if path in paths:
            raise SelectionError(f"run {entry['run']} is listed twice")
        paths.append(path)
    return paths, sel


FIXTURES = json.loads((ROOT / "fixtures" / "manifest.json").read_text(encoding="utf-8"))["fixtures"]


def _latest(where: str, results_dir: Path = ROOT / "results", batch: str | None = None) -> list[Path]:
    """Result files of one batch for ``where``: ``batch`` if given, else the most recent one."""
    found: list[tuple[str, Path]] = []
    for p in sorted(results_dir.glob("*.json")):
        d = json.loads(p.read_text(encoding="utf-8"))
        if d["environment"]["where"] == where:
            found.append((d.get("batch") or d["run_id"], p))
    if batch is not None:
        return [p for b, p in found if b == batch]
    if not found:
        return []
    last = found[-1][0]
    return [p for b, p in found if b == last]


def _f(v: object, pct: bool = True) -> str:
    if v is None:
        return "n/a"
    if isinstance(v, float) and pct:
        return f"{v * 100:.1f}"
    return str(v)


def _secs(v: float | None) -> str:
    if v is None:
        return "—"
    return f"{v * 1000:.0f} ms" if v < 1 else f"{v:.2f} s"


def build(paths: list[Path], colab_batch: str | None = None, selection: dict | None = None) -> str:
    runs = [json.loads(p.read_text(encoding="utf-8")) for p in paths]
    allowed = {e["run"]: set(e["adapters"]) for e in selection["selected"]} if selection else {}
    res: dict[tuple[str, str], dict] = {}
    excluded: list[tuple[str, dict]] = []
    for r in runs:
        for rec in r["results"]:
            if selection and rec["adapter"] not in allowed[r["run_id"]]:
                excluded.append((r["run_id"], rec))
                continue
            key = (rec["adapter"], rec["fixture"])
            if selection and key in res:
                raise SelectionError(f"{key} is selected twice")
            res[key] = rec | {"_run": r["run_id"]}
    L: list[str] = [
        "<!-- Generated by `python -m bench.report`. Do not edit by hand. -->",
        "",
        "# Parser benchmark results tables",
        "",
    ]
    L.append(
        "Scores are percentages (0–100, higher is better). `n/a`: the parser has no such output. "
        "Times are the median of the warm runs; `cold` is the first call, including any model loading."
    )
    L.append("")
    L.append("## Runs")
    L.append("")
    if colab_batch is not None:
        n = sum(1 for r in runs if r["environment"]["where"] == "colab")
        L.append(f"Colab batch `{colab_batch}`: {n} result file(s) merged with the latest laptop run.")
        L.append("")
    L.append("| Run | Where | Hardware | Python | Packages |")
    L.append("| --- | --- | --- | --- | --- |")
    for r in runs:
        e = r["environment"]
        hw = f"{e.get('cpu', '?')}, {e.get('cpu_count')} threads, {e.get('ram_gib')} GiB RAM, GPU: {e.get('gpu') or 'none'}"
        pk = ", ".join(f"{k} {v}" for k, v in r["packages"].items())
        L.append(f"| `{r['run_id']}` | {e['where']} | {hw} | {e['python']} | {pk} |")
    L.append("")
    if selection:
        L += _selection_section(runs, selection, excluded)

    pdfs = [f for f in FIXTURES if f["media_type"] == "application/pdf"]
    pdf_adapters = [a for a in ADAPTERS.values() if a.cases & {f["case"] for f in pdfs}]
    for fx in pdfs:
        has_tables = fx["case"] in ("table_heavy_pdf", "scanned_pdf")
        L.append(f"## {fx['id']} ({fx['case']})")
        L.append("")
        head = "| Parser | Where | Text sim. | Word recall | Word prec. | Reading order | Headings |"
        sep = "| --- | --- | ---: | ---: | ---: | ---: | ---: |"
        if has_tables:
            head += " Table cells | Table headers | Values in text |"
            sep += " ---: | ---: | ---: |"
        else:
            head += " Spurious tables |"
            sep += " ---: |"
        head += " Median | Cold | Status |"
        sep += " ---: | ---: | --- |"
        L += [head, sep]
        for a in pdf_adapters:
            rec = res.get((a.name, fx["id"]))
            row = f"| {a.label} | {a.where} |"
            ncols = 5 + (3 if has_tables else 1)
            if rec is None:
                row += (
                    " — |" * ncols + " — | — | **PENDING** (Colab) |"
                    if a.where == "colab"
                    else " — |" * ncols + " — | — | not run |"
                )
            elif rec["status"] != "ok":
                row += " — |" * ncols + f" — | — | {rec['status']}: {rec.get('error', '')[:120]} |"
            else:
                m = rec["metrics"]
                row += f" {_f(m['text_similarity'])} | {_f(m['word_recall'])} | {_f(m['word_precision'])} | {_f(m['reading_order'])} | {_f(m.get('heading_recall'))} |"
                if has_tables:
                    row += f" {_f(m.get('table_cells'))} | {_f(m.get('table_headers'))} | {_f(m.get('table_values_in_text'))} |"
                else:
                    row += f" {_f(m.get('spurious_tables'))} |"
                row += f" {_secs(rec['median_s'])} | {_secs(rec['cold_s'])} | ok |"
            L.append(row)
        L.append("")

    for case, title in (("csv", "CSV"), ("xlsx", "Workbook")):
        fxs = [f for f in FIXTURES if f["case"] == case]
        adapters = [a for a in ADAPTERS.values() if case in a.cases]
        L.append(f"## {title} fixtures")
        L.append("")
        if case == "csv":
            L.append(
                "| Parser | Where | Fixture | Fields exact | Fields (ws-normalised) | Rows match | Checks | Median | Status |"
            )
            L.append("| --- | --- | --- | ---: | ---: | --- | --- | ---: | --- |")
        else:
            L.append(
                "| Parser | Where | Cell values | Sheets | Hidden sheet | Formulas | Merge kept | Title text | Median | Status |"
            )
            L.append("| --- | --- | ---: | ---: | --- | ---: | ---: | ---: | ---: | --- |")
        for a in adapters:
            for fx in fxs:
                rec = res.get((a.name, fx["id"]))
                status = "**PENDING** (Colab)" if a.where == "colab" else "not run"
                if case == "csv":
                    if rec is None or rec["status"] != "ok":
                        st = status if rec is None else f"{rec['status']}: {rec.get('error', '')[:100]}"
                        L.append(f"| {a.label} | {a.where} | {fx['id']} | — | — | — | — | — | {st} |")
                    else:
                        m = rec["metrics"]
                        ck = ", ".join(f"{k} {_f(v)}" for k, v in m["checks"].items())
                        L.append(
                            f"| {a.label} | {a.where} | {fx['id']} | {_f(m['field_exact'])} | {_f(m['field_normalized'])} | "
                            f"{'yes' if m['rows_match'] else 'no'} ({m['rows_extracted']}/{m['rows_gold']}) | {ck} | {_secs(rec['median_s'])} | ok |"
                        )
                else:
                    if rec is None or rec["status"] != "ok":
                        st = status if rec is None else f"{rec['status']}: {rec.get('error', '')[:100]}"
                        L.append(f"| {a.label} | {a.where} | — | — | — | — | — | — | — | {st} |")
                    else:
                        m = rec["metrics"]
                        L.append(
                            f"| {a.label} | {a.where} | {_f(m['cell_values'])} | {_f(m['sheets_found'])} | {m['hidden_sheet']} | "
                            f"{_f(m['formulas'])} | {_f(m.get('merged_title'))} | {_f(m.get('title_text'))} | {_secs(rec['median_s'])} | ok |"
                        )
        if case == "xlsx":
            L.append("")
            L.append(
                "*Merge kept*: the expected sheet reports the merged range `A1:D1` with the title in its top-left "
                "cell (`n/a`: the parser exposes no merge metadata). *Title text*: the title appears in the "
                "expected sheet as plain text, which earns no merge credit. *Hidden sheet* `unknown`: the parser "
                "exposes no visibility, or names no sheets, so its output cannot show whether the hidden sheet "
                "was kept and marked."
            )
        L.append("")

    by_table = [
        (k, v) for k, v in sorted(res.items()) if v.get("status") == "ok" and v["metrics"].get("table_cells_by_table")
    ]
    if by_table:
        L.append("## Table body cells by table")
        L.append("")
        gold_tables = {}
        for fx in pdfs:
            g = json.loads((ROOT / "fixtures" / fx["gold"]).read_text(encoding="utf-8"))
            for t in g["tables"]:
                gold_tables[t["id"]] = t["style"]
        L.append("| Parser | Fixture | " + " | ".join(f"{tid}: {style}" for tid, style in gold_tables.items()) + " |")
        L.append("| --- | --- | " + " | ".join("---:" for _ in gold_tables) + " |")
        for (adapter, fixture), rec in by_table:
            cells = rec["metrics"]["table_cells_by_table"]
            L.append(
                f"| {ADAPTERS[adapter].label} | {fixture} | "
                + " | ".join(_f(cells.get(t)) if t in cells else "" for t in gold_tables)
                + " |"
            )
        L.append("")

    routing = next((r["routing"] for r in runs if r.get("routing")), None)
    if routing:
        L.append("## Routing check (spec step 1: text layer or scan?)")
        L.append("")
        L.append("| Fixture | Pages | Text chars | Pages with images | Route |")
        L.append("| --- | ---: | ---: | ---: | --- |")
        for r in routing:
            L.append(f"| {r['fixture']} | {r['pages']} | {r['text_chars']} | {r['pages_with_images']} | {r['route']} |")
        L.append("")

    pending = [
        (a, f) for a in ADAPTERS.values() for f in FIXTURES if f["case"] in a.cases and (a.name, f["id"]) not in res
    ]
    L.append("## Pending and not run")
    L.append("")
    if pending:
        L.append(f"{len(pending)} adapter/fixture pairs have no result yet:")
        L.append("")
        for a, f in pending:
            L.append(f"- `{a.name}` × `{f['id']}` — {a.where}; models: {a.uses_models}")
    else:
        L.append("Every planned adapter/fixture pair has a result.")
    L.append("")
    for name, why in CLOUD_CANDIDATES.items():
        L.append(f"- **{name}**: {why}")
    L.append("")
    L.append("## Adapter configurations")
    L.append("")
    L.append("| Adapter | Where | Configuration | Learned models |")
    L.append("| --- | --- | --- | --- |")
    for a in ADAPTERS.values():
        L.append(f"| `{a.name}` | {a.where} | {a.config.replace('|', chr(92) + '|')} | {a.uses_models} |")
    L.append("")
    return "\n".join(L)


def _selection_section(runs: list[dict], selection: dict, excluded: list[tuple[str, dict]]) -> list[str]:
    by_id = {r["run_id"]: r for r in runs}
    L = ["## Run selection", ""]
    L.append(
        f"Results come from `results/{SELECTION}` ({selection['decided_by']}): each adapter is taken from one named "
        "run. Every result left out is listed under *Excluded results*; none is dropped silently."
    )
    zip_info = selection.get("colab_zip")
    if zip_info:
        L += [
            "",
            f"Colab evidence: `{zip_info['file']}`, SHA-256 `{zip_info['sha256']}`, kept unchanged at {zip_info['kept_at']}; imported to {zip_info['imported_to']}.",
        ]
    L += ["", "| Run | Where | Adapters used | Pairs used (ok / failed) | Reason |", "| --- | --- | --- | --- | --- |"]
    for e in selection["selected"]:
        recs = [x for x in by_id[e["run"]]["results"] if x["adapter"] in e["adapters"]]
        okn = sum(1 for x in recs if x["status"] == "ok")
        names = ", ".join(f"`{a}`" for a in e["adapters"])
        L.append(f"| `{e['run']}` | {e['where']} | {names} | {len(recs)} ({okn} / {len(recs) - okn}) | {e['reason']} |")
    L += ["", "### Excluded results", ""]
    if not excluded:
        L += ["None.", ""]
        return L
    L += ["| Run | Adapter | Fixture | Status | Error |", "| --- | --- | --- | --- | --- |"]
    for run_id, rec in excluded:
        err = (rec.get("error") or "").replace("|", "\\|")[:160]
        L.append(f"| `{run_id}` | `{rec['adapter']}` | {rec['fixture']} | {rec['status']} | {err} |")
    L.append("")
    return L


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("paths", nargs="*", type=Path)
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--results-dir", type=Path, default=ROOT / "results")
    ap.add_argument("--colab-batch", help="use this Colab batch instead of the most recent one")
    ap.add_argument("--out", type=Path, default=OUT)
    args = ap.parse_args(argv)
    selection = None
    if args.paths:
        paths = args.paths
    elif args.colab_batch is None and (args.results_dir / SELECTION).exists():
        paths, selection = load_selection(args.results_dir)
    else:
        laptop = _latest("laptop", args.results_dir)
        paths = [*laptop, *_latest("colab", args.results_dir, args.colab_batch)]
    text = build(paths, args.colab_batch, selection) + "\n"
    if args.check:
        if not args.out.exists() or args.out.read_text(encoding="utf-8") != text:
            print(f"{args.out} is stale; run python -m bench.report")
            return 1
        print("results tables are current")
        return 0
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(text, encoding="utf-8")
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
